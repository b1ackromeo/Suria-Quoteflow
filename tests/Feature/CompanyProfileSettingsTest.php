    public function test_company_profile_formats_dates_numbers_money_and_percentages(): void
    {
        $company = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'EUR',
            'date_format' => 'Y-m-d',
            'number_format' => 'de-DE',
        ]));

        $this->assertSame('2026-05-20', $company->formatDate('2026-05-20'));
        $this->assertSame('-', $company->formatDate(null));
        $this->assertSame('1.234,56', $company->formatNumber(1234.56));
        $this->assertSame('EUR 1.234,56', $company->formatMoney(1234.56));
        $this->assertSame('USD 1.234,56', $company->formatMoney(1234.56, 'USD'));
        $this->assertSame('9,00%', $company->formatPercent(9));
    }

    public function test_company_profile_formats_expanded_number_formats(): void
    {
        $india = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'INR',
            'currency_display' => 'code',
            'number_format' => 'en-IN',
        ]));
        $switzerland = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'CHF',
            'currency_display' => 'code',
            'number_format' => 'de-CH',
        ]));
        $japan = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'JPY',
            'currency_display' => 'code',
            'number_format' => 'ja-JP',
        ]));
        $korea = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'KRW',
            'currency_display' => 'code',
            'number_format' => 'ko-KR',
        ]));

        $this->assertSame('12,34,567.89', $india->formatNumber(1234567.89));
        $this->assertSame('INR 12,34,567.89', $india->formatMoney(1234567.89));
        $this->assertSame("CHF 1'234.56", $switzerland->formatMoney(1234.56));
        $this->assertSame('JPY 1,235', $japan->formatMoney(1234.56));
        $this->assertSame('KRW 1,235', $korea->formatMoney(1234.56));
    }

    public function test_malaysia_money_defaults_to_rm_symbol(): void
    {
        $company = new CompanyProfile(CompanyProfile::defaults());

        $this->assertSame('symbol', $company->currencyDisplay());
        $this->assertSame('RM', $company->currencySymbol('MYR'));
        $this->assertSame('RM 1,234.56', $company->formatMoney(1234.56));
    }

    public function test_company_profile_can_use_symbol_and_code_money_display(): void
    {
        $company = new CompanyProfile(array_merge(CompanyProfile::defaults(), [
            'base_currency' => 'MYR',
            'currency_display' => 'symbol_with_code',
            'currency_symbol_override' => 'RM',
            'number_format' => 'en-MY',
        ]));

        $this->assertSame('RM (MYR)', $company->currencyDisplayLabel());
        $this->assertSame('RM 1,234.56 (MYR)', $company->formatMoney(1234.56));
    }
}
